"""C2 mapping engine against golden statements (plan 0004 step E; AGENT_SPEC §9.2).

Golden outputs (`*.expected.json`) were generated by the engine and checked by
hand against the source XML for the totals the identity checks use; every run
also re-derives each fact's value from its `source_element_path`, independently
of the engine's own walk.
"""

import copy
import json
import re
from collections.abc import Callable
from decimal import Decimal
from pathlib import Path

import pytest
from lxml import etree

from distress_radar.parsing.canonical_schema import MappingConfig
from distress_radar.parsing.containers import Element, safe_parser
from distress_radar.parsing.mapping_engine import MappingError, ParsedStatement, parse_statement
from distress_radar.parsing.version_detection import detect
from distress_radar.parsing.xsd_validation import XsdValidator

FIXTURES_DIR = Path(__file__).parent.parent / "fixtures"
STATEMENTS_DIR = FIXTURES_DIR / "statements"
# Every committed fixture, so a new one is covered without editing this file.
GOLDEN = sorted(STATEMENTS_DIR.glob("*.xml")) + [FIXTURES_DIR / "neobis_001.xml"]
TNS_2018 = "http://www.mf.gov.pl/schematy/SF/DefinicjeTypySprawozdaniaFinansowe/2018/07/09/JednostkaInnaWZlotych"
TNS_2018_TYS = "http://www.mf.gov.pl/schematy/SF/DefinicjeTypySprawozdaniaFinansowe/2018/07/09/JednostkaInnaWTysiacach"
JIN_2018 = "http://www.mf.gov.pl/schematy/SF/DefinicjeTypySprawozdaniaFinansowe/2018/07/09/JednostkaInnaStruktury"
DTSF_2018 = "http://www.mf.gov.pl/schematy/SF/DefinicjeTypySprawozdaniaFinansowe/2018/07/09/DefinicjeTypySprawozdaniaFinansowe/"


def load(path: Path) -> etree._Element:
    return etree.fromstring(path.read_bytes(), safe_parser())


def parse(root: etree._Element, config: MappingConfig) -> ParsedStatement:
    detection = detect(root, config)
    assert detection.spec is not None, detection.key
    return parse_statement(root, detection.spec, config)


def expected_path(xml: Path) -> Path:
    return STATEMENTS_DIR / f"{xml.stem}.expected.json"


def as_json(parsed: ParsedStatement) -> dict[str, object]:
    return {
        "structure_version": parsed.structure_version,
        "period_start": parsed.period_start.isoformat(),
        "period_end": parsed.period_end.isoformat(),
        "facts": [
            [
                f.line_item,
                f.column,
                f.statement_type,
                f.variant,
                str(f.value),
                f.source_element_path,
            ]
            for f in parsed.facts
        ],
    }


@pytest.mark.parametrize("xml", GOLDEN, ids=lambda p: p.stem)
def test_golden_statement_matches_expected(xml: Path, mapping_config: MappingConfig) -> None:
    parsed = parse(load(xml), mapping_config)
    assert as_json(parsed) == json.loads(expected_path(xml).read_text(encoding="utf-8"))


@pytest.mark.parametrize("xml", GOLDEN, ids=lambda p: p.stem)
def test_every_fact_resolves_to_its_source_element(
    xml: Path, mapping_config: MappingConfig
) -> None:
    root = load(xml)
    parsed = parse(root, mapping_config)
    spec = mapping_config.specs[parsed.structure_version]
    assert parsed.facts
    for fact in parsed.facts:
        assert isinstance(fact.value, Decimal)
        nodes = root.xpath(fact.source_element_path, namespaces=spec.namespaces)
        assert isinstance(nodes, list) and nodes, fact.source_element_path
        # A user-line total cites every contributing element (an XPath union).
        assert len(nodes) == fact.source_element_path.count(" | ") + 1
        total = sum(
            (Decimal((n.text or "").strip()) for n in nodes if isinstance(n, Element)), Decimal(0)
        )
        assert total * parsed.unit_multiplier == fact.value


def test_identity_totals_by_hand(mapping_config: MappingConfig) -> None:
    """Values read straight from the 2022 golden file, independently of the engine."""
    parsed = parse(load(STATEMENTS_DIR / "full_2018_v1_2_por_2022.xml"), mapping_config)
    facts = {(f.line_item, f.column): f.value for f in parsed.facts}
    root = load(STATEMENTS_DIR / "full_2018_v1_2_por_2022.xml")
    ns = {"t": TNS_2018, "j": JIN_2018, "d": DTSF_2018}

    def text(path: str) -> Decimal:
        [node] = root.xpath(path, namespaces=ns)  # type: ignore[misc]
        return Decimal(node.text)  # type: ignore[union-attr]

    assert facts[("BS.ASSETS", "current_year")] == text(
        "/t:JednostkaInna/t:Bilans/j:Aktywa/d:KwotaA"
    )
    assert facts[("BS.EQUITY_LIABILITIES", "prior_year")] == text(
        "/t:JednostkaInna/t:Bilans/j:Pasywa/d:KwotaB"
    )
    assert facts[("IS.COMP.L", "current_year")] == text(
        "/t:JednostkaInna/t:RZiS/j:RZiSPor/j:L/d:KwotaA"
    )
    assert parsed.unit_multiplier == 1


@pytest.mark.parametrize("xml", GOLDEN, ids=lambda p: p.stem)
def test_income_statement_variants_are_never_mixed(
    xml: Path, mapping_config: MappingConfig
) -> None:
    """A document uses exactly one income-statement layout, never two.

    Three exist: the comparative and calculation variants of the full and small
    forms, and the micro form's own single layout, which is neither (ADR 0005
    second addendum §4) and so carries `variant: "n/a"`.
    """
    layouts = {"COMP": "comparative", "CALC": "calculation", "MIKRO": "n/a"}
    parsed = parse(load(xml), mapping_config)
    income = {
        f.line_item.split(".")[1] for f in parsed.facts if f.statement_type == "income_statement"
    }
    assert len(income) == 1 and income <= set(layouts), income
    variants = {f.variant for f in parsed.facts if f.statement_type == "income_statement"}
    assert variants == {layouts[next(iter(income))]}


