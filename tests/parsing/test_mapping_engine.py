def _add_user_line(parent: etree._Element, slot: int, amount: str) -> None:
    line = etree.SubElement(parent, f"{{{JIN_2018}}}PozycjaUszczegolawiajaca_{slot}")
    etree.SubElement(line, f"{{{DTSF_2018}}}NazwaPozycji").text = "Podróże służbowe"
    amounts = etree.SubElement(line, f"{{{DTSF_2018}}}KwotyPozycji")
    etree.SubElement(amounts, f"{{{DTSF_2018}}}KwotaA").text = amount
    etree.SubElement(amounts, f"{{{DTSF_2018}}}KwotaB").text = "0.00"


def test_user_lines_are_summed_into_one_fact(mapping_config: MappingConfig) -> None:
    root = load(STATEMENTS_DIR / "full_2018_v1_2_por_2022.xml")
    costs = root.find(f".//{{{JIN_2018}}}RZiSPor/{{{JIN_2018}}}B")
    assert costs is not None
    _add_user_line(costs, 7, "100.00")
    _add_user_line(costs, 7, "23.45")
    _add_user_line(costs, 9, "1.00")
    parsed = parse(root, mapping_config)
    [fact] = [
        f for f in parsed.facts if (f.line_item, f.column) == ("IS.COMP.B.USER", "current_year")
    ]
    assert fact.value == Decimal("124.45")
    assert fact.source_element_path.count(" | ") == 2
    assert "PozycjaUszczegolawiajaca_7[2]" in fact.source_element_path
